def score_voice_submission(
    expected_text: str,
    audio_bytes: bytes,
    *,
    audio_mime: str = "audio/webm",
    audio_filename: str = "speaking.webm",
    language: Optional[str] = None,
    transcribe_fn: Optional[Any] = None,
) -> dict[str, Any]:
    """End-to-end: transcribe + score.

    Parameters mirror :func:`transcribe_audio`. ``transcribe_fn`` is a
    test seam — pass a callable returning :class:`VoiceTranscription` to
    skip the network call entirely.

    Returns the response body shape used by ``POST /api/voice/score``:

    ::

        {
          "transcript": str,
          "transcript_confidence": float,
          "accuracy_percent": float,
          "phoneme_score": float,
          "word_errors": list,
          "suggestions": list[str],
          "expected_tokens": list[str],
          "transcript_tokens": list[str],
          "provider": str,
          "model": str
        }
    """

    if transcribe_fn is None:
        transcription = transcribe_audio(
            audio_bytes,
            audio_filename=audio_filename,
            audio_mime=audio_mime,
            language=language,
        )
    else:
        transcription = transcribe_fn(
            audio_bytes,
            audio_filename=audio_filename,
            audio_mime=audio_mime,
            language=language,
        )

    score = score_pronunciation(expected_text, transcription.transcript)
    body = {
        "transcript": transcription.transcript,
        "transcript_confidence": round(transcription.confidence, 3),
        "provider": transcription.provider,
        "model": transcription.model,
    }
    body.update(score.as_dict())
    return body


