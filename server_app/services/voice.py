DEFAULT_GROQ_STT_MODEL = "whisper-large-v3-turbo"
DEFAULT_OPENAI_STT_MODEL = "whisper-1"


def voice_provider_name() -> str:
    """Resolve the voice provider name (``groq`` by default)."""

    return os.getenv("LVCODEX_VOICE_PROVIDER", "groq").strip().lower() or "groq"


def voice_provider_config() -> dict[str, Any]:
    """Return ``{provider, api_key, model, base_url, language}`` for the active STT."""

    provider = voice_provider_name()
    if provider == "groq":
        api_key = os.getenv("GROQ_API_KEY", "").strip()
        if not api_key:
            raise VoiceConfigError(
                "GROQ_API_KEY is missing. Set it in the environment to enable "
                "voice transcription, or set LVCODEX_VOICE_PROVIDER=openai."
            )
        return {
            "provider": "groq",
            "api_key": api_key,
            "model": (
                os.getenv("LVCODEX_VOICE_MODEL")
                or os.getenv("GROQ_STT_MODEL")
                or DEFAULT_GROQ_STT_MODEL
            ).strip(),
            "base_url": os.getenv(
                "GROQ_BASE_URL", "https://api.groq.com/openai/v1"
            ).rstrip("/"),
            "language": os.getenv("LVCODEX_VOICE_LANGUAGE", "lv").strip() or "lv",
        }
    if provider == "openai":
        api_key = os.getenv("OPENAI_API_KEY", "").strip()
        if not api_key:
            raise VoiceConfigError(
                "OPENAI_API_KEY is missing. Set it in the environment to use the "
                "OpenAI Whisper STT, or switch back to LVCODEX_VOICE_PROVIDER=groq."
            )
        return {
            "provider": "openai",
            "api_key": api_key,
            "model": (
                os.getenv("LVCODEX_VOICE_MODEL")
                or os.getenv("OPENAI_STT_MODEL")
                or DEFAULT_OPENAI_STT_MODEL
            ).strip(),
            "base_url": os.getenv(
                "OPENAI_BASE_URL", "https://api.openai.com/v1"
            ).rstrip("/"),
            "language": os.getenv("LVCODEX_VOICE_LANGUAGE", "lv").strip() or "lv",
        }
    raise VoiceConfigError(
        f"Unsupported LVCODEX_VOICE_PROVIDER='{provider}'. Use 'groq' or 'openai'."
    )


# ---------------------------------------------------------------------------
# Multipart helper (stdlib-only)
# ---------------------------------------------------------------------------


def _multipart_encode(
    fields: dict[str, str], audio_bytes: bytes, audio_filename: str, audio_mime: str
) -> tuple[bytes, str]:
    """Encode a multipart/form-data body for the audio upload."""

    boundary = "----LVCodexVoiceBoundary7Z9k2"
    crlf = "\r\n"
    parts: list[bytes] = []
    for name, value in fields.items():
        parts.append(f"--{boundary}".encode("utf-8"))
        parts.append(
            f'Content-Disposition: form-data; name="{name}"'.encode("utf-8")
        )
        parts.append(b"")
        parts.append(str(value).encode("utf-8"))
    parts.append(f"--{boundary}".encode("utf-8"))
    parts.append(
        (
            f'Content-Disposition: form-data; name="file"; '
            f'filename="{audio_filename}"'
        ).encode("utf-8")
    )
    parts.append(f"Content-Type: {audio_mime}".encode("utf-8"))
    parts.append(b"")
    parts.append(audio_bytes)
    parts.append(f"--{boundary}--".encode("utf-8"))
    parts.append(b"")
    body = crlf.encode("utf-8").join(parts)
    content_type = f"multipart/form-data; boundary={boundary}"
    return body, content_type


