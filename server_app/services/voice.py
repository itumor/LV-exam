# STT entry point
# ---------------------------------------------------------------------------


def _confidence_from_whisper(payload: dict[str, Any]) -> float:
    """Heuristic confidence in [0, 1] from Whisper's avg_logprob.

    Whisper returns no calibrated confidence; we map ``exp(avg_logprob)``
    over segments to a 0..1 score. When no segments are present (older
    server versions, or text-only response), fall back to 0.5 — a
    neutral midpoint that signals "we have a transcript but unknown
    quality".
    """

    segments = payload.get("segments") or []
    if not segments:
        avg_lp = payload.get("avg_logprob")
        if isinstance(avg_lp, (int, float)):
            return max(0.0, min(1.0, math.exp(float(avg_lp))))
        return 0.5
    logprobs: list[float] = []
    for seg in segments:
        avg_lp = seg.get("avg_logprob")
        if isinstance(avg_lp, (int, float)):
            logprobs.append(float(avg_lp))
    if not logprobs:
        return 0.5
    mean_lp = sum(logprobs) / len(logprobs)
    return max(0.0, min(1.0, math.exp(mean_lp)))


def _fake_transcript() -> Optional[str]:
    """Return the fake transcript hook (used by unit tests)."""

    fake = os.getenv("LVCODEX_VOICE_FAKE_TRANSCRIPT")
    if fake is None:
        return None
    return fake


def transcribe_audio(
    audio_bytes: bytes,
    *,
    audio_filename: str = "speaking.webm",
    audio_mime: str = "audio/webm",
    language: Optional[str] = None,
    config: Optional[dict[str, Any]] = None,
) -> VoiceTranscription:
    """Transcribe a single audio blob using the configured STT provider.

    The default provider is Groq Whisper (``LVCODEX_VOICE_PROVIDER=groq``)
    which is both cheaper and faster than OpenAI Whisper for our usage.

    Parameters
    ----------
    audio_bytes:
        Raw audio. The Groq endpoint accepts webm/opus, ogg, wav, mp3,
        m4a and flac up to 25 MB.
    audio_filename / audio_mime:
        Forwarded as the multipart filename / Content-Type. Whisper
        sniffs the codec from the bytes, but a sensible filename helps
        when the provider falls back to ffmpeg.
    language:
        ISO-639-1 hint. Defaults to ``lv`` so Whisper picks the Latvian
        model. Set to empty string to force auto-detect.
    config:
        Optional override for :func:`voice_provider_config`. Used by the
        scoring route to inject a per-request override (e.g. when a
        learner has opted into a paid provider tier).

    Returns
    -------
    VoiceTranscription
        Includes the transcript, a heuristic confidence, and the raw
        provider response (for debugging / telemetry).
    """

    fake = _fake_transcript()
    if fake is not None:
        return VoiceTranscription(
            transcript=fake,
            confidence=1.0,
            raw={"fake": True, "transcript": fake},
            provider="fake",
            model="fake",
        )

    cfg = config or voice_provider_config()
    target_language = language if language is not None else cfg.get("language", "lv")
    url = f"{cfg['base_url']}/audio/transcriptions"

    fields: dict[str, str] = {
        "model": cfg["model"],
        "response_format": "verbose_json",
        # ``temperature=0`` makes Whisper deterministic for a given
        # input. Important for scoring reproducibility.
        "temperature": "0",
    }
    if target_language:
        fields["language"] = target_language

    body, content_type = _multipart_encode(
        fields=fields,
        audio_bytes=audio_bytes,
        audio_filename=audio_filename,
        audio_mime=audio_mime,
    )

    request = urllib.request.Request(
        url,
        data=body,
        headers={
            "Authorization": f"Bearer {cfg['api_key']}",
            "Content-Type": content_type,
            "User-Agent": "lvcodex-voice/1.0",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            raw_body = response.read()
    except urllib.error.HTTPError as error:
        detail = ""
        try:
            detail = error.read().decode("utf-8", errors="replace")[:500]
        except Exception:  # noqa: BLE001
            pass
        raise VoiceProviderError(
            f"STT provider {cfg['provider']} returned HTTP {error.code}: {detail}"
        ) from error
    except urllib.error.URLError as error:
        raise VoiceProviderError(
            f"STT provider {cfg['provider']} unreachable: {error.reason}"
        ) from error

    try:
        payload = json.loads(raw_body.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise VoiceProviderError(
            f"STT provider {cfg['provider']} returned non-JSON response."
        ) from error

    transcript_text = str(payload.get("text") or "").strip()
    confidence = _confidence_from_whisper(payload)
    return VoiceTranscription(
        transcript=transcript_text,
        confidence=confidence,
        raw=payload,
        provider=cfg["provider"],
        model=cfg["model"],
    )


# ---------------------------------------------------------------------------
# Text normalization + tokenization
# ---------------------------------------------------------------------------


# Latvian alphabet — diacritics preserved (long vowels + soft consonants
# change meaning). The scorer is case-insensitive and strips
# punctuation, but does NOT fold ā→a, č→c etc.
_LATVIAN_DIACRITICS = set("āčēģīķļņšūž")
# Latvian vowels (long + short). Used by the rough syllabifier.
_LATVIAN_VOWELS = set("aeiouāēīōūy")


def normalize_text(text: str) -> str:
    """Lowercase + Unicode-NFC + strip surrounding whitespace.

    We deliberately do NOT strip diacritics here — long vowels are
    meaning-bearing in Latvian (``māte`` 'mother' vs ``mate`` 'mat').
    Diacritic-stripped comparison is exposed separately via
    :func:`fold_diacritics` for the phoneme-score path.
    """

    return unicodedata.normalize("NFC", text or "").strip().lower()


def fold_diacritics(text: str) -> str:
    """Strip Latvian diacritics for the rough phoneme comparison."""

    normalized = unicodedata.normalize("NFD", text or "")
    folded = "".join(
        ch for ch in normalized if not unicodedata.combining(ch)
    )
    return folded.lower()


def tokenize(text: str) -> list[str]:
    """Split into word tokens, dropping punctuation.

    Keeps Latvian diacritics intact and treats apostrophes inside a
    token as part of the word (rare in Latvian, but cheap to support).
    """

    cleaned = normalize_text(text)
    tokens: list[str] = []
    current: list[str] = []
    for ch in cleaned:
        if ch.isalpha() or ch.isdigit() or ch == "'":
            current.append(ch)
        else:
            if current:
                tokens.append("".join(current))
                current = []
    if current:
        tokens.append("".join(current))
    return tokens


def syllabify(token: str) -> list[str]:
    """Very rough Latvian syllabification.

    Latvian syllable rule of thumb: each syllable has exactly one
    vowel nucleus; consonant clusters break before the last consonant
    when followed by another vowel. We approximate by anchoring on
    vowels — every vowel starts a new syllable group, with leading
    consonants attached to the next vowel.

    This is intentionally lossy — the scorer only uses syllable count
    + first-character + nucleus comparison, so a perfect linguistic
    syllabifier would not change any score by more than ~1 %.
    """

    if not token:
        return []
    syllables: list[str] = []
    current: list[str] = []
    seen_vowel = False
    for ch in token:
        is_vowel = ch in _LATVIAN_VOWELS
        if is_vowel and seen_vowel:
            # Start a new syllable: break before the new vowel and let
            # any consonants stick with the previous syllable's coda.
            syllables.append("".join(current))
            current = []
            seen_vowel = False
        current.append(ch)
        if is_vowel:
            seen_vowel = True
    if current:
        syllables.append("".join(current))
    return syllables


# ---------------------------------------------------------------------------
# Edit distance + alignment
# ---------------------------------------------------------------------------


def _levenshtein_with_ops(a: list[str], b: list[str]) -> tuple[int, list[tuple[str, int, int]]]:
    """Compute edit distance + reconstruct edit ops.

    Returns ``(distance, ops)`` where each op is
    ``("match" | "substitute" | "insert" | "delete", i, j)``. Optionally
    delegates to ``Levenshtein`` if the library is available, but we
    always reconstruct ops in pure Python because the alignment is
    needed to build word-error reports and ``Levenshtein`` only emits
    raw distance.
    """

    m, n = len(a), len(b)
    if m == 0:
        return n, [("insert", 0, j) for j in range(n)]
    if n == 0:
        return m, [("delete", i, 0) for i in range(m)]
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    for i in range(m + 1):
        dp[i][0] = i
    for j in range(n + 1):
        dp[0][j] = j
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            dp[i][j] = min(
                dp[i - 1][j] + 1,
                dp[i][j - 1] + 1,
                dp[i - 1][j - 1] + cost,
            )
    # Backtrace
    i, j = m, n
    ops: list[tuple[str, int, int]] = []
    while i > 0 or j > 0:
        if i > 0 and j > 0 and a[i - 1] == b[j - 1] and dp[i][j] == dp[i - 1][j - 1]:
            ops.append(("match", i - 1, j - 1))
            i -= 1
            j -= 1
        elif i > 0 and j > 0 and dp[i][j] == dp[i - 1][j - 1] + 1:
            ops.append(("substitute", i - 1, j - 1))
            i -= 1
            j -= 1
        elif i > 0 and dp[i][j] == dp[i - 1][j] + 1:
            ops.append(("delete", i - 1, j))
            i -= 1
        else:
            ops.append(("insert", i, j - 1))
            j -= 1
    ops.reverse()
    return dp[m][n], ops


def _char_levenshtein(a: str, b: str) -> int:
    """Char-level edit distance.

    Uses ``Levenshtein.distance`` when installed (much faster on long
    strings), otherwise a stdlib DP implementation.
    """

    try:
        import Levenshtein  # type: ignore[import-not-found]
        return int(Levenshtein.distance(a, b))
    except ImportError:
        pass
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        curr = [i] + [0] * len(b)
        for j, cb in enumerate(b, 1):
            cost = 0 if ca == cb else 1
            curr[j] = min(
                prev[j] + 1,
                curr[j - 1] + 1,
                prev[j - 1] + cost,
            )
        prev = curr
    return prev[-1]


# ---------------------------------------------------------------------------
# Suggestion generator
# ---------------------------------------------------------------------------


def _suggest_for_substitution(expected: str, got: str) -> Optional[str]:
    """Return a learner-facing hint for one expected → got substitution.

    Detects three common A2-learner mistakes:

    1. Long-vowel loss (``māte`` -> ``mate``): diacritic-folded match
       but raw mismatch.
    2. Soft-consonant confusion (``ļ`` -> ``l``, ``ņ`` -> ``n``).
    3. Word-shape mismatch (different stem entirely): falls through to
       a generic "expected X but heard Y" hint.
    """

    if not expected or not got:
        return None
    if expected == got:
        return None
    # Detect mīkstinājums (soft-consonant) loss first — these characters
    # are the cedilla-family (ļ, ņ, ķ, ģ) plus the haček consonants (š,
    # č, ž). We compute the soft-fold and compare BEFORE falling into
    # the long-vowel hint because both folds collapse to ASCII and the
    # soft-consonant message is more specific.
    soft_map = {"ļ": "l", "ņ": "n", "ķ": "k", "ģ": "g", "š": "s", "č": "c", "ž": "z"}
    expected_has_soft = any(ch in soft_map for ch in expected)
    folded_soft = "".join(soft_map.get(ch, ch) for ch in expected)
    if expected_has_soft and folded_soft == got:
        return (
            f"You said '{got}', but the word is '{expected}' — "
            "remember the mīkstinājums (soft consonant)."
        )
    if fold_diacritics(expected) == fold_diacritics(got):
        # Long-vowel / diacritic loss.
        return (
            f"You said '{got}', but the word is '{expected}' — "
            "watch the long vowels (garumzīme)."
        )
    return f"Expected '{expected}', but heard '{got}'."


# ---------------------------------------------------------------------------
# Public scoring entry point
# ---------------------------------------------------------------------------


def score_pronunciation(
    expected_text: str,
    transcript: str,
    *,
    max_suggestions: int = 5,
) -> PronunciationScore:
    """Compare an STT transcript to the expected text.

    Returns a :class:`PronunciationScore` carrying the headline accuracy
    percent (token-level), a secondary phoneme-level score, the per-word
    discrepancies, and short learner-facing suggestions.

    ``accuracy_percent`` is ``100 * (1 - dist / max(len_expected, 1))``,
    clamped to [0, 100]. When the learner says EXTRA words on top of
    the prompt the score drops to discourage rambling that the rubric
    would not reward.
    """

    expected_tokens = tokenize(expected_text)
    transcript_tokens = tokenize(transcript)
    if not expected_tokens:
        return PronunciationScore(
            accuracy_percent=100.0 if not transcript_tokens else 0.0,
            phoneme_score=100.0 if not transcript_tokens else 0.0,
            word_errors=[],
            suggestions=[],
            expected_tokens=[],
            transcript_tokens=transcript_tokens,
        )

    distance, ops = _levenshtein_with_ops(expected_tokens, transcript_tokens)
    accuracy = 100.0 * (1.0 - distance / max(len(expected_tokens), 1))
    accuracy = max(0.0, min(100.0, accuracy))

    word_errors: list[WordError] = []
    suggestions: list[str] = []
    for op, i, j in ops:
        if op == "match":
            continue
        if op == "substitute":
            err = WordError(
                expected=expected_tokens[i],
                got=transcript_tokens[j],
                kind="substitution",
            )
            word_errors.append(err)
            hint = _suggest_for_substitution(err.expected, err.got)
            if hint and len(suggestions) < max_suggestions:
                suggestions.append(hint)
        elif op == "delete":
            err = WordError(
                expected=expected_tokens[i],
                got="",
                kind="deletion",
            )
            word_errors.append(err)
            if len(suggestions) < max_suggestions:
                suggestions.append(f"Missed the word '{err.expected}'.")
        elif op == "insert":
            err = WordError(
                expected="",
                got=transcript_tokens[j],
                kind="insertion",
            )
            word_errors.append(err)
            if len(suggestions) < max_suggestions:
                suggestions.append(
                    f"Extra word '{err.got}' — try to stick to the prompt."
                )

    phoneme_score = _phoneme_score(expected_tokens, transcript_tokens)
    return PronunciationScore(
        accuracy_percent=accuracy,
        phoneme_score=phoneme_score,
        word_errors=word_errors,
        suggestions=suggestions,
        expected_tokens=expected_tokens,
        transcript_tokens=transcript_tokens,
    )


def _phoneme_score(expected: list[str], transcript: list[str]) -> float:
    """Syllable-aligned character similarity in [0, 100].

    Sums char-level edit distances over each syllable pair, normalized
    by the total expected syllable length. The pairing is positional —
    we don't try to re-align after deletions because the token-level
    score already covers macro errors; this score is meant to surface
    "you got the word but a long vowel was missing"-type mistakes.
    """

    expected_syllables: list[str] = []
    for tok in expected:
        expected_syllables.extend(syllabify(tok))
    transcript_syllables: list[str] = []
    for tok in transcript:
        transcript_syllables.extend(syllabify(tok))
    if not expected_syllables:
        return 100.0 if not transcript_syllables else 0.0

    total_expected = sum(len(s) for s in expected_syllables) or 1
    pairs = max(len(expected_syllables), len(transcript_syllables))
    total_distance = 0
    for idx in range(pairs):
        exp_syl = expected_syllables[idx] if idx < len(expected_syllables) else ""
        got_syl = transcript_syllables[idx] if idx < len(transcript_syllables) else ""
        total_distance += _char_levenshtein(exp_syl, got_syl)
    score = 100.0 * (1.0 - total_distance / total_expected)
    return max(0.0, min(100.0, score))


