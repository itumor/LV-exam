"""Voice synth / recognition + pronunciation scoring (T-046).

Wraps a speech-to-text (STT) provider and a deterministic pronunciation
scorer so the speaking-capture flow introduced by T-018 can return an
``accuracy_percent`` to the learner after they submit a recording.

Provider choice
---------------
The plan calls for the cheaper / faster of OpenAI Whisper vs Groq
Whisper — Groq Whisper wins on both axes (Groq's distil-large-v3 is
≈ $0.04/hr vs OpenAI's $0.36/hr, and Groq's published p95 RTF is
≈ 200× faster than realtime on whisper-large-v3-turbo). The provider
hits Groq's OpenAI-compatible ``/audio/transcriptions`` endpoint by
default; override via ``LVCODEX_VOICE_PROVIDER=openai`` if Groq is
down (the OpenAI endpoint is wire-compatible).

The provider call is mediated through :func:`transcribe_audio` which
returns ``VoiceTranscription(transcript, confidence, raw)``. The
``confidence`` field is a heuristic on top of Whisper's
``avg_logprob`` (Whisper does not emit a calibrated 0..1 score; we map
``exp(avg_logprob)`` clipped to [0, 1]).

Pronunciation scoring
---------------------
:func:`score_pronunciation` compares the STT transcript to the expected
Latvian text and returns:

* ``accuracy_percent`` — 100 - normalized edit distance, on the cleaned
  token stream (case-folded, punctuation stripped, diacritics retained
  because Latvian's long-vowel marks change meaning, e.g. ``māte`` vs
  ``mate``).
* ``word_errors`` — list of ``{expected, got, kind}`` triples, where
  ``kind`` is one of ``"substitution" | "insertion" | "deletion"``.
* ``suggestions`` — short, learner-facing hints ("you said 'mate' but
  the word is 'māte' — long ā"). Generated by a tiny phoneme-shape
  comparison on the substitution pairs (rough Latvian syllabification:
  vowels are anchors, garumzīme adds weight).
* ``phoneme_score`` — secondary score derived from syllable-aligned
  character similarity. Useful as a tie-breaker when learners get the
  words right but mangle a long vowel.

The scorer is deterministic and offline; no LLM is used here so it does
not consume the T-026 AI quota (only the upstream STT call does, and
that uses a separate "voice" quota slot — see :func:`score_voice_submission`).

Test seam
---------
For tests, set ``LVCODEX_VOICE_FAKE_TRANSCRIPT`` to short-circuit the
HTTP call and return a canned transcript. The unit tests in
``tests/server/test_voice_service.py`` use this hook so they don't need
network access or API keys.
"""

