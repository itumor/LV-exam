# ---------------------------------------------------------------------------
# Public dataclasses
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class VoiceTranscription:
    """STT result returned by :func:`transcribe_audio`."""

    transcript: str
    confidence: float
    raw: dict[str, Any] = field(default_factory=dict)
    provider: str = "groq"
    model: str = ""


@dataclass(frozen=True)
class WordError:
    """Single token-level discrepancy between expected and actual text."""

    expected: str
    got: str
    kind: str  # "substitution" | "insertion" | "deletion"


@dataclass(frozen=True)
class PronunciationScore:
    """Output of :func:`score_pronunciation`."""

    accuracy_percent: float
    phoneme_score: float
    word_errors: list[WordError]
    suggestions: list[str]
    expected_tokens: list[str]
    transcript_tokens: list[str]

    def as_dict(self) -> dict[str, Any]:
        return {
            "accuracy_percent": round(self.accuracy_percent, 1),
            "phoneme_score": round(self.phoneme_score, 1),
            "word_errors": [
                {
                    "expected": err.expected,
                    "got": err.got,
                    "kind": err.kind,
                }
                for err in self.word_errors
            ],
            "suggestions": list(self.suggestions),
            "expected_tokens": list(self.expected_tokens),
            "transcript_tokens": list(self.transcript_tokens),
        }


