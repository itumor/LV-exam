def load_audio_from_t018(
    audio_url: str,
    *,
    upload_store: Any,
    user_id: str,
    upload_root: Optional[Path] = None,
) -> tuple[bytes, str]:
    """Resolve an audio_url coming from T-018 to ``(bytes, mime)``.

    Two URL shapes are supported:

    * ``/api/uploads/speaking/<attempt_id>/<task_id>`` — the new T-018
      layout. We load directly from the ``upload_store`` to avoid
      re-encoding the bytes through an HTTP round-trip.
    * ``/api/uploads/speaking/<upload_id>`` — the legacy single-id
      layout from the original ``store_speaking_upload``. We read the
      ``*.meta.json`` and return the referenced file.

    Raises :class:`FileNotFoundError` if the upload cannot be found and
    :class:`PermissionError` if the URL does not point inside the
    user's own scope (cross-user access is denied — admins use the
    upload route's ``?user_id=`` override, not this helper).
    """

    parsed = urllib.parse.urlparse(audio_url)
    path = parsed.path or audio_url
    prefix = "/api/uploads/speaking/"
    if not path.startswith(prefix):
        raise ValueError(
            f"audio_url must start with {prefix!r}, got {audio_url!r}"
        )
    remainder = path[len(prefix):]
    if "/" in remainder:
        parts = remainder.split("/")
        if len(parts) != 2 or not parts[0] or not parts[1]:
            raise FileNotFoundError(f"audio_url malformed: {audio_url!r}")
        attempt_id, task_id = parts
        mime, payload = upload_store.load(
            attempt_id=attempt_id,
            task_id=task_id,
            user_id=user_id,
        )
        return payload, mime

    upload_id = remainder
    if upload_root is None:
        raise FileNotFoundError(
            "upload_root is required to resolve legacy single-id uploads."
        )
    meta_path = upload_root / "speaking" / f"{upload_id}.meta.json"
    if not meta_path.exists():
        raise FileNotFoundError(f"upload metadata missing for {upload_id!r}")
    metadata = json.loads(meta_path.read_text(encoding="utf-8"))
    if metadata.get("account_id") and metadata["account_id"] != user_id:
        raise PermissionError("upload does not belong to this user")
    audio_filename = metadata.get("audio_filename") or ""
    audio_path = (upload_root / "speaking" / audio_filename).resolve()
    speaking_root = (upload_root / "speaking").resolve()
    try:
        audio_path.relative_to(speaking_root)
    except ValueError as error:
        raise PermissionError("upload path escapes storage root") from error
    if not audio_path.exists():
        raise FileNotFoundError(f"audio file missing for {upload_id!r}")
    return audio_path.read_bytes(), metadata.get("content_type", "audio/webm")


